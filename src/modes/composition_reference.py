#!/usr/bin/env python3
"""Regenerate independent Kuznyechik composition fixtures.

Requires gostcrypto==1.2.5, wheel SHA256:
5cfc8b4c33d2a110fea0cfcb693b4a5f2b021004b9cf8d6bba8b78aab23d2001
https://pypi.org/project/gostcrypto/1.2.5/
https://github.com/drobotun/gostcrypto

Only its raw block cipher is used; CMAC, CTR, ACPKM and composition formatting
below are independent Python implementations. They do not invoke this Zig repo.
The complete ciphertexts are stored verbatim in composition_oracle.bin; the
Zig fixture index includes lengths and SHA256 for reproducibility.
RFC9337 has no cipher composition KAT (Appendix A is PBKDF2 only).
"""
from hashlib import sha256
from pathlib import Path
from gostcrypto.gostcipher.gost_34_12_2015 import GOST34122015Kuznechik


def cipher(key):
    return GOST34122015Kuznechik(bytearray(key))


def encrypt(c, block):
    return bytes(c.encrypt(bytearray(block)))


def xor(a, b):
    return bytes(x ^ y for x, y in zip(a, b))


def double(block):
    n = int.from_bytes(block, 'big')
    return (((n << 1) & ((1 << 128) - 1)) ^ (0x87 if n >> 127 else 0)).to_bytes(16, 'big')


def cmac(key, data):
    c = cipher(key)
    k1 = double(encrypt(c, bytes(16)))
    k2 = double(k1)
    complete = bool(data) and len(data) % 16 == 0
    before = (len(data) - 1) // 16 * 16 if data else 0
    state = bytes(16)
    for at in range(0, before, 16):
        state = encrypt(c, xor(state, data[at:at+16]))
    tail = data[before:]
    if not complete:
        tail = tail + b'\x80' + bytes(15 - len(tail))
    return encrypt(c, xor(state, xor(tail, k1 if complete else k2)))


def ctr(key, nonce, data, section=0):
    c = cipher(key)
    result = b''
    for at in range(0, len(data), 16):
        if section and at and at % section == 0:
            key = encrypt(c, bytes(range(128, 144))) + encrypt(c, bytes(range(144, 160)))
            c = cipher(key)
        counter = nonce + (at // 16).to_bytes(8, 'big')
        result += xor(data[at:at+16], encrypt(c, counter))
    return result


def protect(enc_key, mac_key, nonce, prefix, data, section=0):
    return ctr(enc_key, nonce, data + cmac(mac_key, prefix + data), section)


def official_self_checks():
    mac = bytes.fromhex('7dac56e48a4dc170faa8fcbae20db845450cccc4c6328bdc8d01157cefa2a5f1')
    enc = bytes.fromhex('1f1cbad8866166f01ffaab0152e24bf4609d5f46a5c899c787900d08b9fcad24')
    nonce = bytes.fromhex('214a6a298e99e325')
    secret = bytes.fromhex('a5576ce7924a24f58113808dbd9ef856f5bdc3b183ce5dadca36a53aa077651d')
    assert protect(enc, mac, nonce, nonce, secret).hex() == (
        '250d1b67a270ab04d3f65418e1d380b4cb945f0a3dca51500cf3a1bef37f76c0'
        '7341a9839ccf6cba7189da61eb67176c')
    mac = bytes.fromhex('19a76ed30f4d6d1f5b7263ec491ad83817c0b57d8a0356127140fb4f7425494d')
    enc = bytes.fromhex('58afbe9a4c3198aaabaa2692c419f1797c9b92deb3cc7446b363577113f0fb56')
    prefix = bytes.fromhex('0000000000000000170303000f')
    assert cmac(mac, prefix + bytes(15)).hex() == 'fd1719dd950837eb7c7bb8f500379981'
    assert protect(enc, mac, bytes(8), prefix, bytes(15), 4096).hex() == (
        '4d1a305236573bffc14e46dcbe746db6c99a175a81c4711e2f84c392c5407c')


def main():
    official_self_checks()
    enc, mac, nonce = bytes(range(32)), bytes(range(32, 64)), bytes(range(8))
    lengths = [0, 1, 15, 16, 17, 31, 32, 33, 63, 64, 65, 1007, 1008,
               1009, 1023, 1024, 1025, 4079, 4080, 4081, 4095, 4096,
               4097, 8191, 8192, 8193, 17408]
    index, binary = [], bytearray()
    for kind, sections in [('kexp', [0]), ('tls', [4096]), ('password', [16, 32, 1024, 4096])]:
        for section in sections:
            for length in lengths:
                data = bytes((i * 29 + 7) % 256 for i in range(length))
                if kind == 'tls':
                    seq = 0xffffffffffffffff
                    # Base IV 0001020304050607 plus seq wraps to ..0606.
                    iv = ((int.from_bytes(nonce, 'big') + seq) % (1 << 64)).to_bytes(8, 'big')
                    prefix = seq.to_bytes(8, 'big') + bytes([23, 3, 3]) + length.to_bytes(2, 'big')
                else:
                    iv = nonce
                    prefix = nonce if kind == 'kexp' else b''
                result = protect(enc, mac, iv, prefix, data, section)
                index.append((kind, section, length, len(binary), len(result), sha256(result).hexdigest()))
                binary.extend(result)
    path = Path(__file__).parent
    path.joinpath('composition_oracle.bin').write_bytes(binary)
    with path.joinpath('composition_oracle.zig').open('w') as out:
        out.write('//! Generated by composition_reference.py using gostcrypto1.2.5 raw Kuznyechik.\n')
        out.write('//! Independent reference outputs, NOT official RFC9337 vectors.\n')
        out.write('const hex = @import("test_helpers.zig").hex;\n')
        out.write(f'pub const encryption_key = hex("{enc.hex()}");\n')
        out.write(f'pub const authentication_key = hex("{mac.hex()}");\n')
        out.write('pub const data = @embedFile("composition_oracle.bin");\n')
        out.write('pub const Kind = enum { kexp, tls, password };\n')
        out.write('pub const Case = struct { kind: Kind, section: usize, length: usize, offset: usize, size: usize, sha256: [32]u8 };\n')
        out.write('pub const cases = blk: {\n    @setEvalBranchQuota(200000);\n    break :blk [_]Case{\n')
        for kind, section, length, offset, size, digest in index:
            out.write(f'    .{{ .kind = .{kind}, .section = {section}, .length = {length}, .offset = {offset}, .size = {size}, .sha256 = hex("{digest}") }},\n')
        out.write('    };\n};\n')
    print(f'{len(index)} vectors, {len(binary)} bytes, SHA256 {sha256(binary).hexdigest()}')


if __name__ == '__main__':
    main()
