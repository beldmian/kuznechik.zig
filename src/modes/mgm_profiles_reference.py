#!/usr/bin/env python3
"""Independent fixture generator, no Zig code imported.

Dependency: gostcrypto==1.2.5 raw Kuznyechik only, wheel SHA256
5cfc8b4c33d2a110fea0cfcb693b4a5f2b021004b9cf8d6bba8b78aab23d2001.
MGM polynomial arithmetic, counters and profile formatting below are independent.
RFC source snapshots live in docs/validation/mgm-profiles. Published derived
keys are used directly, so this fixture generator needs no external KDF.
"""
from pathlib import Path
from hashlib import sha256
import re
from gostcrypto.gostcipher.gost_34_12_2015 import GOST34122015Kuznechik

BASE = Path(__file__).resolve().parent
RFC = BASE.parent.parent / 'docs/validation/mgm-profiles'
MASK = (1 << 128) - 1

def xor(a, b):
    return bytes(x ^ y for x, y in zip(a, b))

def mul(a, b):
    r = 0
    while b:
        if b & 1:
            r ^= a
        a = ((a << 1) & MASK) ^ (0x87 if a >> 127 else 0)
        b >>= 1
    return r

def mgm(key, nonce, aad, data):
    c = GOST34122015Kuznechik(bytearray(key))
    def e(b):
        return bytes(c.encrypt(bytearray(b)))
    assert nonce[0] < 128 and aad + data
    z = e(bytes([nonce[0] | 128]) + nonce[1:])
    y = e(nonce)
    enc = b''
    for at in range(0, len(data), 16):
        enc += xor(data[at:at+16], e(y))
        y = y[:8] + ((int.from_bytes(y[8:], 'big')+1) % (1 << 64)).to_bytes(8, 'big')
    lengths = (len(aad)*8).to_bytes(8, 'big') + (len(enc)*8).to_bytes(8, 'big')
    total = 0
    for stream in (aad, enc, lengths):
        for at in range(0, len(stream), 16):
            block = stream[at:at+16].ljust(16, b'\0')
            total ^= mul(int.from_bytes(e(z), 'big'), int.from_bytes(block, 'big'))
            z = ((int.from_bytes(z[:8], 'big')+1) % (1 << 64)).to_bytes(8, 'big') + z[8:]
    return enc, e(total.to_bytes(16, 'big'))

def dump(text):
    return [(int(k,16), bytes.fromhex(v)) for k,v in re.findall(r'^ +([0-9A-F]{5,8}): +([0-9A-F ]+)$', text, re.M)]

def field(record, label):
    return dump(record.split(label+':',1)[1].split('\n\n',1)[0])

def unhex(record, label):
    out = field(record, label)
    assert all(at == sum(len(b) for _, b in out[:i]) for i,(at,_) in enumerate(out))
    return b''.join(b for _,b in out)

binary = bytearray()
def store(b):
    at = len(binary)
    binary.extend(b)
    return f'blob[{at}..][0..{len(b)}]'

def hx(b):
    return f'hex("{b.hex()}")'

out = ['//! Generated by mgm_profiles_reference.py. See docs/mgm-profiles.md.',
       'const hex = @import("test_helpers.zig").hex;',
       'pub const blob = @embedFile("mgm_profiles_oracle.bin");',
       'pub const TlsCase = struct { sequence: u64, key: [32]u8, iv: [16]u8, plaintext: []const u8, ciphertext_tag: []const u8 };',
       'pub const tls = blk: { @setEvalBranchQuota(200000); break :blk [_]TlsCase{']
# RFC9367 A.1 has 17 Kuznyechik records; A.2 is Magma, deliberately excluded.
s = RFC.joinpath('rfc9367.txt').read_text().rsplit('A.2.  Example 2',1)[0]
write_ivs = [b''.join(v for _,v in dump(m)) for m in re.findall(r'(?:server|client)_write_iv_(?:hs|ap) = [^\n]*:\n([^\n]+)', s)]
assert len(write_ivs) == 4
records = re.split(r'\n +(?:server|client)_record_write_key = TLSTREE\([^\n]*, (\d+)\):', s)
for i in range(1, len(records), 2):
    seq, r = int(records[i]), records[i+1]
    key = b''.join(v for _, v in dump(r.split('seqnum:',1)[0]))
    nonce = unhex(r,'nonce')
    aad = unhex(r,'additional_data')
    length = int.from_bytes(aad[3:], 'big')-16
    rows = field(r, 'TLSInnerPlaintext')
    plain = bytearray(length)
    covered = set()
    for at,b in rows:
        assert at + len(b) <= length
        plain[at:at+len(b)] = b
        covered.update(range(at,at+len(b)))
    # The only omitted plaintexts are explicitly all-zero application data
    # with padding (see A.1). The type byte at offset1024 is published.
    if len(covered) < length:
        assert length == 16385 and plain[1024] == 23
        assert all(b == 0 for j,b in enumerate(plain) if j != 1024)
    enc, tag = mgm(key, nonce, aad, bytes(plain))
    wire = aad + enc + tag
    samples = field(r, 'TLSCiphertext')
    for at,b in samples:
        assert wire[at:at+len(b)] == b, (i//2,at,wire[at:at+len(b)].hex(),b.hex())
    # Select the exact published write IV, undoing sequence XOR and comparing
    # with its top bit masked (the RFC prints the masked nonce).
    masked_iv = nonce[:8] + xor(nonce[8:], seq.to_bytes(8,'big'))
    candidates = [iv for iv in write_ivs if bytes([iv[0]&127])+iv[1:] == masked_iv]
    assert len(candidates) == 1
    iv = candidates[0]
    out.append(f'    .{{ .sequence={seq}, .key={hx(key)}, .iv={hx(iv)}, .plaintext={store(plain)}, .ciphertext_tag={store(enc+tag)} }},')
    print(f'RFC9367 A.1 record {i//2}: seq {seq}, plaintext {length}, checked {sum(len(b) for _,b in samples)} published wire bytes')
assert (len(records)-1)//2 == 17
out += ['}; };',
        'pub const EspCase = struct { mac_only: bool, material: [44]u8, key: [32]u8, iv: [8]u8, nonce: [16]u8, aad: []const u8, plaintext: []const u8, ciphertext: []const u8, tag: [12]u8 };',
        'pub const esp = blk: { @setEvalBranchQuota(200000); break :blk [_]EspCase{']
s = RFC.joinpath('rfc9227.txt').read_text()
for number in (1,2,5,6):
    r = s.split(f'   {number}.  ENCR_',1)[1].split('\n   '+str(number+1)+'.  ENCR_',1)[0]
    def f(label):
        m = re.search(r'^      '+re.escape(label)+r' \[(\d+)\]:\n((?:          [0-9a-f ]+\n)*)',r,re.M)
        b = bytes.fromhex(m[2]); assert len(b)==int(m[1]); return b
    material, key, iv, nonce, aad, plain, enc, tag = [f(label) for label in ('transform key','K_msg','IV','nonce','AAD','plaintext','ciphertext','ESP ICV')]
    got, full = mgm(key,nonce,aad,plain)
    assert got == enc and full[:12] == tag
    out.append(f'    .{{ .mac_only={str(number>2).lower()}, .material={hx(material)}, .key={hx(key)}, .iv={hx(iv)}, .nonce={hx(nonce)}, .aad={store(aad)}, .plaintext={store(plain)}, .ciphertext={store(enc)}, .tag={hx(tag)} }},')
    print(f'RFC9227 Appendix A example {number}: all published cipher fields match')
out += ['}; };',
        'pub const OracleCase = struct { aad_len: usize, length: usize, encrypted: []const u8, tag: [16]u8 };',
        'pub const independent = blk: { @setEvalBranchQuota(200000); break :blk [_]OracleCase{']
# Independent synthetic inputs stress nonaligned AAD concatenation and MGM
# short/long boundaries; these are explicitly NOT official RFC vectors.
key = bytes(range(32)); nonce = bytes(range(16))
for a,n in [(0,1),(1,0),(1,1),(15,17),(16,32),(17,31),(31,33),(32,0),(33,65),(1007,481),(1008,496),(1009,497),(1023,1023),(1024,1024),(1025,1025),(1057,2081)]:
    aad = bytes((j*17+3)%256 for j in range(a))
    data = bytes((j*29+7)%256 for j in range(n))
    enc, tag = mgm(key,nonce,aad,data)
    out.append(f'    .{{ .aad_len={a}, .length={n}, .encrypted={store(enc)}, .tag={hx(tag)} }},')
out += ['}; };']
BASE.joinpath('mgm_profiles_oracle.bin').write_bytes(binary)
BASE.joinpath('mgm_profiles_vectors.zig').write_text('\n'.join(out)+'\n')
print(f'blob size {len(binary)}, SHA256 {sha256(binary).hexdigest()}')
