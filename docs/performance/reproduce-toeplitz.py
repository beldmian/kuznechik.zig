"""Reproduce the fixed Kuznechik L factorization and operation graph.

Python3 standard library only. This derives all constants from the original
16 recurrence coefficients, searches the 255 geometric normalizations,
validates every single-byte value, and writes the exact normalized DAG.
It does not search arbitrary common subexpressions: it only canonicalizes
identical primitive XOR/multiply nodes generated by the Toeplitz recursion.
"""
from collections import Counter
from functools import lru_cache
import json
from pathlib import Path

C = [148,32,133,16,194,192,1,251,1,192,194,16,133,32,148,1]

def gf(a, b):
    out = 0
    for _ in range(8):
        if b & 1:
            out ^= a
        a = ((a << 1) ^ (0x1c3 if a & 128 else 0)) & 255
        b >>= 1
    return out

M = [[gf(a,b) for b in range(256)] for a in range(256)]
def power(a,n):
    out = 1
    while n:
        if n & 1:
            out = M[out][a]
        a = M[a][a]
        n >>= 1
    return out

def inv(a):
    assert a
    return power(a,254)

def xor(values):
    out = 0
    for v in values:
        out ^= v
    return out

def linear(x, inverse=False):
    x = list(x)
    for _ in range(16):
        if inverse:
            f = x[0] ^ xor(M[C[i]][x[i+1]] for i in range(15))
            x = x[1:] + [f]
        else:
            x = [xor(M[a][b] for a,b in zip(C,x))] + x[:-1]
    return x

# Exact matrix, then determine diagonal equivalence to Toeplitz. Adjacent
# diagonal ratios must factor as a row-ratio times a column-ratio.
L = list(map(list,zip(*(linear([int(i==j) for i in range(16)]) for j in range(16)))))
R = [[M[L[i+1][j+1]][inv(L[i][j])] for j in range(15)] for i in range(15)]
assert all(M[R[i][j]][R[0][0]] == M[R[i][0]][R[0][j]] for i in range(15) for j in range(15))
row = [1]
col = [1]
for i in range(15):
    row.append(M[row[-1]][inv(R[i][0])])
for j in range(15):
    col.append(M[col[-1]][M[R[0][0]][inv(R[0][j])]])
T = [[M[row[i]][M[L[i][j]][col[j]]] for j in range(16)] for i in range(16)]
assert all(T[i][j] == T[i+1][j+1] for i in range(15) for j in range(15))

def leaf_coefficients(t):
    n = len(t)
    if n == 1:
        return [t[0][0]]
    m = n // 2
    a = [r[:m] for r in t[:m]]
    b = [r[m:] for r in t[:m]]
    c = [r[:m] for r in t[m:]]
    return (leaf_coefficients(a)
            + leaf_coefficients([[a[i][j]^b[i][j] for j in range(m)] for i in range(m)])
            + leaf_coefficients([[a[i][j]^c[i][j] for j in range(m)] for i in range(m)]))

# D_row L D_column = T has a geometric degree of freedom q^(i-j).
# A global scalar gamma normalizes the most common nonzero leaf to1.
best = None
for q in range(1,256):
    qp = [power(q,i) for i in range(16)]
    qi = [inv(v) for v in qp]
    t = [[M[qp[i]][M[v][qi[j]]] for j,v in enumerate(r)] for i,r in enumerate(T)]
    cs = leaf_coefficients(t)
    value,count = Counter(v for v in cs if v).most_common(1)[0]
    score = (len(cs)-cs.count(0)-count,-count,q,inv(value))
    if best is None or score < best:
        best = score
_,_,q,gamma = best
rs = [M[power(q,i)][v] for i,v in enumerate(row)]
cs = [M[gamma][M[power(inv(q),i)][v]] for i,v in enumerate(col)]
t = [[M[gamma][M[power(q,(i-j)%255)][v]] for j,v in enumerate(r)] for i,r in enumerate(T)]
# Split the otherwise free global diagonal scale to maximize unit diagonals.
a,units = Counter([inv(v) for v in rs]+cs).most_common(1)[0]
rs = [M[a][v] for v in rs]
cs = [M[inv(a)][v] for v in cs]
assert all(t[i][j] == M[rs[i]][M[L[i][j]][cs[j]]] for i in range(16) for j in range(16))

class DAG:
    def __init__(self):
        self.nodes = [('zero',)]+[('input',i) for i in range(16)]
        self.cache = {node:i for i,node in enumerate(self.nodes)}
    def node(self,t):
        if t not in self.cache:
            self.cache[t] = len(self.nodes)
            self.nodes.append(t)
        return self.cache[t]
    def xor(self,a,b):
        if a == b: return 0
        if not a: return b
        if not b: return a
        return self.node(('xor',min(a,b),max(a,b)))
    def prod(self,x,c):
        if not x or not c: return 0
        if c == 1: return x
        return self.node(('mul',x,c))
    def reachable(self,outputs):
        seen = set()
        def visit(i):
            if i in seen: return
            seen.add(i)
            t = self.nodes[i]
            for j in t[1:] if t[0]=='xor' else t[1:2] if t[0]=='mul' else []:
                visit(j)
        for i in outputs: visit(i)
        return seen
    def evaluate(self,outputs,x):
        values = [0]*len(self.nodes)
        for i in sorted(self.reachable(outputs)):
            n = self.nodes[i]
            if n[0]=='input': values[i] = x[n[1]]
            elif n[0]=='mul': values[i] = M[values[n[1]]][n[2]]
            elif n[0]=='xor': values[i] = values[n[1]]^values[n[2]]
        return [values[i] for i in outputs]

def transform(d,t,x):
    # Toeplitz block identity: T=[[A,B],[C,A]].
    # p=A(x0+x1), q=(A+B)x1, r=(A+C)x0; y=(p+q,p+r).
    n = len(t)
    if n == 1: return [d.prod(x[0],t[0][0])]
    m = n//2
    aa = [r[:m] for r in t[:m]]
    bb = [r[m:] for r in t[:m]]
    cc = [r[:m] for r in t[m:]]
    p = transform(d,aa,[d.xor(x[i],x[m+i]) for i in range(m)])
    q = transform(d,[[aa[i][j]^bb[i][j] for j in range(m)] for i in range(m)],x[m:])
    r = transform(d,[[aa[i][j]^cc[i][j] for j in range(m)] for i in range(m)],x[:m])
    return [d.xor(p[i],q[i]) for i in range(m)]+[d.xor(p[i],r[i]) for i in range(m)]

d = DAG()
outputs = transform(d,t,list(range(1,17)))
seen = d.reachable(outputs)
used = {i:0 for i in seen}
for i in seen:
    n = d.nodes[i]
    for j in n[1:] if n[0]=='xor' else n[1:2] if n[0]=='mul' else []:
        used[j] += 1
for i in outputs: used[i] += 1
live = set()
peak = 0
for i in sorted(seen):
    if d.nodes[i][0]=='zero': continue
    live.add(i)
    peak = max(peak,len(live))
    n = d.nodes[i]
    for j in n[1:] if n[0]=='xor' else n[1:2] if n[0]=='mul' else []:
        used[j] -= 1
        if used[j] == 0: live.discard(j)
@lru_cache(None)
def depth(i):
    n = d.nodes[i]
    if n[0] in ('input','zero'): return 0
    if n[0]=='mul': return depth(n[1])+3
    return max(depth(n[1]),depth(n[2]))+1
stats = dict(gfni=sum(d.nodes[i][0]=='mul' for i in seen),
             xor=sum(d.nodes[i][0]=='xor' for i in seen),
             peak_live_values=peak,modeled_depth_cycles=max(map(depth,outputs)))
assert stats == dict(gfni=75,xor=194,peak_live_values=32,modeled_depth_cycles=11)
for position in range(16):
    for value in range(256):
        x = [0]*16
        x[position] = value
        scaled = [M[inv(c)][v] for c,v in zip(cs,x)]
        y = [M[inv(c)][v] for c,v in zip(rs,d.evaluate(outputs,scaled))]
        assert y == linear(x)
        # L-inverse is J L J: reverse input and output around the same map.
        rev = x[::-1]
        scaled = [M[inv(c)][v] for c,v in zip(cs,rev)]
        yi = [M[inv(c)][v] for c,v in zip(rs,d.evaluate(outputs,scaled))][::-1]
        assert yi == linear(x,True)
proof = dict(field_polynomial='0x1c3',recurrence=C,q=q,gamma=gamma,normalization_a=a,
             row_scale=rs,column_scale=cs,matrix=t,nodes=d.nodes,outputs=outputs,
             stats=stats,validated_single_byte_values_per_direction=4096)
Path(__file__).with_name('toeplitz-proof.json').write_text(json.dumps(proof,indent=2)+'\n')
print(json.dumps({k:proof[k] for k in ['q','gamma','normalization_a','stats']}))
