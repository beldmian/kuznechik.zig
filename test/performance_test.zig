const std = @import("std");
const kuznechik = @import("../src/kuznechik.zig");

const expect = std.testing.expect;

test "Performance optimization correctness" {
    // Test that our optimizations don't break functionality
    const k = kuznechik.key{ 
        0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff, 
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 
        0xfe, 0xdc, 0xba, 0x98, 0x76, 0x54, 0x32, 0x10, 
        0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef 
    };
    
    var original_msg = kuznechik.block{ 
        0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x00, 
        0xff, 0xee, 0xdd, 0xcc, 0xbb, 0xaa, 0x99, 0x88 
    };
    
    const expected_encrypted = kuznechik.block{ 
        0x7f, 0x67, 0x9d, 0x90, 0xbe, 0xbc, 0x24, 0x30, 
        0x5a, 0x46, 0x8d, 0x42, 0xb9, 0xd4, 0xed, 0xcd 
    };
    
    const cipher = kuznechik.Cipher.init(k);
    
    // Test encryption
    var msg_copy = original_msg;
    cipher.encrypt(&msg_copy);
    try expect(std.mem.eql(u8, &msg_copy, &expected_encrypted));
    
    // Test decryption
    cipher.decrypt(&msg_copy);
    try expect(std.mem.eql(u8, &msg_copy, &original_msg));
}

test "Multiple encrypt/decrypt cycles" {
    const k = kuznechik.key{ 
        0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff, 
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 
        0xfe, 0xdc, 0xba, 0x98, 0x76, 0x54, 0x32, 0x10, 
        0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef 
    };
    
    const original_msg = kuznechik.block{ 
        0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x00, 
        0xff, 0xee, 0xdd, 0xcc, 0xbb, 0xaa, 0x99, 0x88 
    };
    
    const cipher = kuznechik.Cipher.init(k);
    
    // Test multiple cycles to ensure consistency
    var msg = original_msg;
    for (0..1000) |_| {
        cipher.encrypt(&msg);
        cipher.decrypt(&msg);
        try expect(std.mem.eql(u8, &msg, &original_msg));
    }
}