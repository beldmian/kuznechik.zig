const coeff = [16]u8{ 148, 32, 133, 16, 194, 192, 1, 251, 1, 192, 194, 16, 133, 32, 148, 1 };
fn mul(x: u8, y: u8) u8 {
    var product: u16 = 0;
    for (0..8) |i| if ((y >> @intCast(i)) & 1 != 0) {
        product ^= @as(u16, x) << @intCast(i);
    };
    var i: usize = 15;
    while (i >= 8) : (i -= 1) {
        if ((product & (@as(u16, 1) << @intCast(i))) != 0) product ^= @as(u16, 0x1c3) << @intCast(i - 8);
    }
    return @truncate(product);
}
fn linear(input: Block) Block {
    var a = input;
    for (0..16) |_| {
        var v: u8 = 0;
        for (a, coeff) |x, c| v ^= mul(x, c);
        var b: Block = undefined;
        b[0] = v;
        @memcpy(b[1..], a[0..15]);
        a = b;
    }
    return a;
}
pub fn inverseLinear(input: Block) Block {
    var a = input;
    for (0..16) |_| {
        var b: Block = undefined;
        @memcpy(b[0..15], a[1..16]);
        var v = a[0];
        for (0..15) |i| v ^= mul(b[i], coeff[i]);
        b[15] = v;
        a = b;
    }
    return a;
}
pub fn expand(key: [32]u8) [10]Block {
    var result: [10]Block = undefined;
    var a = key[0..16].*;
    var b = key[16..32].*;
    result[0] = a;
    result[1] = b;
    for (0..32) |round| {
        var c: Block = @splat(0);
        c[15] = @intCast(round + 1);
        c = linear(c);
        var t: Block = undefined;
        for (0..16) |i| t[i] = pi[a[i] ^ c[i]];
        t = linear(t);
        for (0..16) |i| t[i] ^= b[i];
        b = a;
        a = t;
        if (round % 8 == 7) {
            result[2 + (round / 8) * 2] = a;
            result[3 + (round / 8) * 2] = b;
        }
    }
    return result;
}
/// Reverse eight Feistel steps to recover the preceding round-key pair.
pub fn previousPair(next_a: Block, next_b: Block, group: usize) [2]Block {
    var a = next_a;
    var b = next_b;
    var round = (group + 1) * 8;
    while (round > group * 8) {
        var c: Block = @splat(0);
        c[15] = @intCast(round);
        c = linear(c);
        var t: Block = undefined;
        for (0..16) |i| t[i] = pi[b[i] ^ c[i]];
        t = linear(t);
        for (0..16) |i| t[i] ^= a[i];
        a = b;
        b = t;
        round -= 1;
    }
    return .{ a, b };
}
